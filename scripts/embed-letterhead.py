"""Regenerate src/lib/letterheadData.ts after assets/brand/letterhead.jpeg changes: python scripts/embed-letterhead.py"""
import base64
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
b = base64.b64encode((root / 'assets/brand/letterhead.jpeg').read_bytes()).decode()
(root / 'src/lib/letterheadData.ts').write_text(
    "/**\n * The company letterhead picture (assets/brand/letterhead.jpeg), as base64 inside the JavaScript bundle.\n"
    " * In a release APK a bundled image is an Android resource with no file path (\"URI is not absolute\"), so\n"
    " * reading it as a file failed and every letterhead PDF came out plain. Generated by scripts/embed-letterhead.py.\n */\n"
    f"export const LETTERHEAD_JPEG_BASE64 =\n  '{b}';\n",
    encoding='utf-8',
)
